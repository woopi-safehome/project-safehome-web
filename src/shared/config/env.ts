/**
 * 브라우저까지 내려가는 값은 전부 공개된 것으로 다룬다.
 * 서버 비밀값을 여기에 두지 않는다 — 번들에 그대로 들어간다.
 */
export const env = {
  /**
   * 서버 호출은 **이 앱의 주소로** 보낸다. 비워 두는 것이 기본이며, 그러면 `/api/...` 가
   * 같은 출처 요청이 되어 쿠키가 실린다. 넘길 백엔드 주소는 `next.config.ts` 가 갖는다.
   *
   * 값을 넣으면 브라우저가 백엔드를 **직접** 부른다 — 교차 출처가 되어 비회원 분석의
   * 주인을 가리는 쿠키가 실리지 않는다. 그 사정을 아는 경우에만 쓴다.
   */
  apiUrl: process.env.NEXT_PUBLIC_API_URL ?? "",
  /**
   * 카카오 JavaScript 키. **없으면 로그인 화면이 버튼을 잠근다.**
   * 앱의 네이티브 키와 다른 값이며, 카카오 콘솔에 이 웹 주소를 플랫폼으로 등록해야 한다.
   */
  kakaoJsKey: process.env.NEXT_PUBLIC_KAKAO_JS_KEY ?? "",
} as const;
